uint8_t g711_ulaw_encode(int16_t pcm)
{
    int mag = pcm;
    uint8_t mask = 0xFF;
    int seg = 0;

    if (mag < 0) {
        mag = -mag;
        mask = 0x7F;
    }
    if (mag > ULAW_CLIP) {
        mag = ULAW_CLIP;
    }
    mag += ULAW_BIAS;
    while (seg < 7 && mag >= (0x100 << seg)) {
        seg++;
    }
    return (uint8_t)(((seg << 4) | ((mag >> (seg + 3)) & 0x0F)) ^ mask);
}

int16_t g711_ulaw_decode(uint8_t code)
{
    return s_ulaw_dec[code];
}

uint8_t g711_alaw_encode(int16_t pcm)
{
    /* 13-bit magnitude; floor((-p-1)/8) for negatives avoids shifting a negative value. */
    int mag;
    uint8_t mask;
    int seg = 0;
    int aval;

    if (pcm >= 0) {
        mag = pcm >> 3;
        mask = 0xD5;
    } else {
        mag = (-(pcm + 1)) >> 3;
        mask = 0x55;
    }
    while (seg < 7 && mag >= (0x20 << seg)) {
        seg++;
    }
    aval = seg << 4;
    aval |= (seg < 2) ? ((mag >> 1) & 0x0F) : ((mag >> seg) & 0x0F);
    return (uint8_t)(aval ^ mask);
}

int16_t g711_alaw_decode(uint8_t code)
{
    return s_alaw_dec[code];
}

void g711_ulaw_encode_buf(const int16_t *pcm, uint8_t *out, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        out[i] = g711_ulaw_encode(pcm[i]);
    }
}

void g711_ulaw_decode_buf(const uint8_t *in, int16_t *pcm, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        pcm[i] = s_ulaw_dec[in[i]];
    }
}

void g711_alaw_encode_buf(const int16_t *pcm, uint8_t *out, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        out[i] = g711_alaw_encode(pcm[i]);
    }
}

